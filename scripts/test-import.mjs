import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {prepareBatch} from '../batch-import.js';
import {reviewBatch} from '../batch-merge.js';
import {roundProgress} from '../round-progress.js';
import {scoreLineup,scoreTeam} from '../scoring-policy.js';
const load=name=>JSON.parse(readFileSync(new URL('../'+name,import.meta.url),'utf8'));
const players=load('jugadores.json'),coaches=load('entrenadores.json');
const teams=[...new Set(players.map(p=>p.team))];
const matches=teams.map((team,i)=>({id:'test-'+i,team,status:'finished',forGoals:0,againstGoals:0,events:[]}));
const first=reviewBatch({},prepareBatch(matches.slice(0,10),players,coaches));
assert.equal(roundProgress(teams,first.next.results,true).pending.length,teams.length-10);
const second=reviewBatch(first.next,prepareBatch(matches.slice(10),players,coaches));
assert.equal(roundProgress(teams,second.next.results,true).state,'finished');
for(const p of players)assert.equal(second.next.scores[p.id],['POR','DEF'].includes(p.pos)?4:1);
for(const c of coaches)assert.equal(second.next.scores[c.id],2);
const repeat=reviewBatch(second.next,prepareBatch(matches,players,coaches));
assert.equal(repeat.unchangedCount,teams.length);
assert.deepEqual(repeat.next,second.next);
const corrected={...matches[0],againstGoals:1};
const fix=reviewBatch(second.next,prepareBatch([corrected],players,coaches));
assert.equal(fix.correctedCount,1);
for(const p of players)assert.equal(fix.next.scores[p.id],p.team===corrected.team?0:second.next.scores[p.id]);
const slots=players.slice(0,11).map(p=>p.id),coachId=coaches[0].id;
assert.equal(scoreLineup({slots,coachId,captainId:slots[0]},second.next.scores),slots.reduce((s,id)=>s+second.next.scores[id],0)+second.next.scores[coachId]+second.next.scores[slots[0]]);
console.log('OK: importaciones parciales, puntuaciones, repetición, rectificación y capitán');


const conflicting={...matches[0],team:teams[1]};
assert.throws(()=>reviewBatch(first.next,prepareBatch([conflicting],players,coaches)),/otra categoría/);
const invalid={...matches[0],forGoals:2,events:[]};
assert.equal(prepareBatch([invalid],players,coaches).canPublish,false);
assert.equal(prepareBatch([matches[0],matches[0]],players,coaches).canPublish,false);

const samplePlayers=[{id:'g',team:'A',pos:'POR'},{id:'d',team:'A',pos:'DEF'},{id:'m',team:'A',pos:'MED'},{id:'f',team:'A',pos:'DEL'},{id:'other',team:'B',pos:'DEL'}];
const sampleCoaches=[{id:'c',team:'A'}];
const win=scoreTeam(samplePlayers,sampleCoaches,'A',{result:'win',cleanSheet:true,goals:{f:4},reds:{d:1}});
assert.deepEqual(win,{g:6,d:1,m:3,f:12,c:5});
assert.equal(scoreLineup({slots:['g','d','m','f'],coachId:'c',captainId:'f'},win),39);
const loss=scoreTeam(samplePlayers,sampleCoaches,'A',{result:'loss',cleanSheet:false,goals:{m:1},reds:{f:1}});
assert.deepEqual(loss,{g:0,d:0,m:3,f:-5,c:0});
assert.equal(scoreLineup({slots:['g','d','m','f'],coachId:'c',captainId:'f'},loss),-7);
assert.deepEqual(scoreTeam(samplePlayers,sampleCoaches,'A',{result:'draw',cleanSheet:true}),{g:4,d:4,m:1,f:1,c:2});
assert.equal(scoreLineup({slots:['g'],coachId:'c',captainId:'g'},{g:0}),0);
assert.throws(()=>scoreTeam(samplePlayers,sampleCoaches,'A',{result:'invalid'}));
